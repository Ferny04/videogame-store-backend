-- Run once in the empty videogame_store database.
BEGIN;

CREATE TABLE public.consolas (
    id_consola integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(45) NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
    estado boolean NOT NULL
);

CREATE TABLE public.clientes (
    id varchar(20) PRIMARY KEY CHECK (btrim(id) <> ''),
    nombre varchar(40) NOT NULL CHECK (btrim(nombre) <> ''),
    apellidos varchar(100),
    celular varchar(25),
    direccion varchar(80),
    correo_electronico varchar(70)
);

CREATE TABLE public.videojuegos (
    id_videojuego integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL CHECK (btrim(nombre) <> ''),
    id_consola integer NOT NULL REFERENCES public.consolas(id_consola),
    precio_venta numeric(16, 2) NOT NULL CHECK (precio_venta >= 0 AND precio_venta <> 'NaN'::numeric),
    cantidad_stock integer NOT NULL CHECK (cantidad_stock >= 0),
    estado boolean NOT NULL
);

CREATE TABLE public.ventas (
    id_venta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente varchar(20) NOT NULL REFERENCES public.clientes(id),
    fecha timestamp without time zone NOT NULL,
    medio_pago varchar(1) NOT NULL CHECK (btrim(medio_pago) <> ''),
    comentario varchar(300),
    estado varchar(1) NOT NULL CHECK (btrim(estado) <> '')
);

CREATE TABLE public.ventas_videojuegos (
    id_venta integer NOT NULL REFERENCES public.ventas(id_venta),
    id_videojuego integer NOT NULL REFERENCES public.videojuegos(id_videojuego),
    cantidad integer NOT NULL CHECK (cantidad > 0),
    total numeric(16, 2) NOT NULL CHECK (total >= 0 AND total <> 'NaN'::numeric),
    estado boolean NOT NULL,
    PRIMARY KEY (id_venta, id_videojuego)
);

CREATE TABLE public.usuarios (
    username varchar(100) PRIMARY KEY CHECK (btrim(username) <> ''),
    password_hash varchar(60) NOT NULL
        CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
);

CREATE INDEX videojuegos_id_consola_idx ON public.videojuegos (id_consola);
CREATE INDEX ventas_id_cliente_idx ON public.ventas (id_cliente);
CREATE INDEX ventas_videojuegos_id_videojuego_idx ON public.ventas_videojuegos (id_videojuego);

COMMIT;
